// Tests the two metadata parsers against real bytes: the `desc` for jq
// out of extra.db as a mirror serves it, and the `.PKGINFO` out of the
// jq package the Internet Archive holds. Both have to land in the same
// shape, because everything downstream reads one PackageMeta and never
// asks which file it came from.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

import { parseDesc, parsePkginfo } from "../../site/js/desc.js";

const read = (name) =>
  readFile(new URL(`../fixtures/${name}`, import.meta.url), "utf8");

test("parseDesc reads a repo database entry", async () => {
  const meta = parseDesc(await read("jq.desc"));

  assert.equal(meta.name, "jq");
  assert.equal(meta.base, "jq");
  assert.equal(meta.version, "1.8.2-1");
  assert.equal(meta.filename, "jq-1.8.2-1-x86_64.pkg.tar.zst");
  assert.equal(meta.desc, "Command-line JSON processor");
  assert.equal(meta.url, "https://jqlang.github.io/jq/");
  assert.equal(meta.arch, "x86_64");
  assert.equal(meta.csize, 213086);
  assert.equal(meta.isize, 492406);
  assert.equal(meta.builddate, 1781975439);
  assert.equal(
    meta.sha256,
    "35f197700d1e8a1692fd67c644c1e57a72f4969707772ac1f477b02351248e1b",
  );
  assert.ok(meta.pgpsig.startsWith("iQIzBAABCgAdFiEE"));
  assert.deepEqual(meta.license, ["MIT"]);
  assert.deepEqual(meta.depends, ["glibc", "oniguruma"]);
  assert.deepEqual(meta.makedepends, [
    "autoconf",
    "automake",
    "bison",
    "flex",
    "git",
    "python",
  ]);
  // Sections the entry does not have are empty, not missing.
  assert.deepEqual(meta.provides, []);
  assert.deepEqual(meta.groups, []);
});

test("parsePkginfo reads a package's own metadata", async () => {
  const meta = parsePkginfo(await read("PKGINFO"));

  assert.equal(meta.name, "jq");
  assert.equal(meta.base, "jq");
  assert.equal(meta.version, "1.7.1-2");
  assert.equal(meta.desc, "Command-line JSON processor");
  assert.equal(meta.url, "https://jqlang.github.io/jq/");
  assert.equal(meta.arch, "x86_64");
  assert.equal(meta.builddate, 1717879231);
  assert.equal(meta.packager, "kpcyrd <kpcyrd@archlinux.org>");
  // `size` in a .PKGINFO is the installed size, which the database
  // calls %ISIZE%.
  assert.equal(meta.isize, 765858);
  assert.deepEqual(meta.depends, ["glibc", "oniguruma"]);
  assert.deepEqual(meta.makedepends, [
    "autoconf",
    "automake",
    "bison",
    "flex",
    "python",
  ]);
  // A package file says nothing about where it is served from or what
  // its compressed size is.
  assert.equal(meta.filename, null);
  assert.equal(meta.csize, null);
  assert.equal(meta.sha256, null);
});

test("each parse gets its own lists", async () => {
  const one = parseDesc(await read("jq.desc"));
  const two = parseDesc("%NAME%\nbash\n\n%DEPENDS%\nreadline\n");
  assert.deepEqual(two.depends, ["readline"]);
  assert.deepEqual(one.depends, ["glibc", "oniguruma"]);
});

test("a .PKGINFO comment is not a field", () => {
  const meta = parsePkginfo(
    [
      "# Generated by makepkg 6.1.0",
      "pkgname = hello",
      "xdata = pkgtype=pkg",
    ].join("\n"),
  );
  assert.equal(meta.name, "hello");
  assert.equal(meta.base, "hello");
});

test("a package with no pkgbase falls back to its name", () => {
  assert.equal(parseDesc("%NAME%\nfoo\n").base, "foo");
});
